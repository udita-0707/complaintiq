"""Deployment record for ``reports/m5/deployment.md`` (M5, SPEC C13 M5).

``--label local --docker-image IMAGE``: starts a fresh container of IMAGE, measures the time
from ``docker run`` to a healthy ``/health`` with the model loaded (cold start), reads
``/v1/model`` and the process memory from ``/metrics``, records the image ID and size, then
stops the container.

``--label public --url URL``: polls the public URL until healthy (run it right after a
Space restart to measure the cold start; otherwise it is just the time to the first healthy
answer), then reads the same endpoints. The image digest is the one Hugging Face built; the
local image ID is listed for reference only.

Writes ``reports/m5/results/deployment_<label>.json`` and re-renders the report from every
label present. Aggregates only.

Usage::

    python scripts/deployment_report.py --label local --docker-image complaintiq-serve:local
    python scripts/deployment_report.py --label public --url https://<user>-complaintiq.hf.space
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
RESULTS = REPO / "reports" / "m5" / "results"
REPORT = REPO / "reports" / "m5" / "deployment.md"
MANIFEST = RESULTS / "model_manifest.json"
LABELS = ("local", "public")

sys.path.insert(0, str(Path(__file__).resolve().parent))
from failure_tests import Container, HttpClient, metric_sum  # noqa: E402


def wait_healthy(client: HttpClient, wait_s: float) -> float:
    start = time.perf_counter()
    while time.perf_counter() - start < wait_s:
        try:
            r = client.request("GET", "/health")
            if r.status == 200 and r.body.get("model_loaded"):
                return time.perf_counter() - start
        except Exception:  # not reachable yet
            pass
        time.sleep(1.0)
    raise SystemExit(f"not healthy after {wait_s:.0f} s")


def collect(client: HttpClient) -> dict[str, Any]:
    health = client.request("GET", "/health").body
    model = client.request("GET", "/v1/model").body
    rss = metric_sum(client.request, "process_resident_memory_bytes")
    return {"health": health, "model_version": model.get("model_version"),
            "predictor": model.get("predictor"), "thresholds": model.get("thresholds"),
            "rss_mb": rss / 1e6 if rss else None}


def image_info(image: str) -> dict[str, Any]:
    out = subprocess.run(["docker", "image", "inspect", image, "--format",
                          "{{.Id}} {{.Size}}"], capture_output=True, text=True, check=True)
    image_id, size = out.stdout.split()
    return {"image": image, "image_id": image_id, "image_size_mb": int(size) / 1e6}


def _git_commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=REPO,
                              capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def _fmt(v: Any, d: int = 1) -> str:
    if v is None:
        return "TODO"
    return f"{v:.{d}f}" if isinstance(v, float) else str(v)


def render(results: dict[str, dict[str, Any]]) -> str:
    manifest = json.loads(MANIFEST.read_text()) if MANIFEST.is_file() else {}
    pub = results.get("public") or {}
    out = [
        "# M5 deployment record",
        "",
        "Generated by `python scripts/deployment_report.py` (`make deployment-report`).",
        "",
        f"- Public API URL: {pub.get('url') or 'TODO (Aman: deploy, then run the public label)'}",
        f"- Reviewer UI URL: {pub.get('ui_url') or 'TODO'}",
        "- Host: Hugging Face Spaces, Docker SDK, free CPU tier; model files in the Space repo "
        "via git-lfs (never in GitHub).",
        f"- Frozen model: `{manifest.get('model_id', 'TODO')}`, model_version "
        f"`{manifest.get('model_version', 'TODO')}`, frozen {manifest.get('frozen_date', 'TODO')}"
        f"; file checksums in `reports/m5/results/model_manifest.json` "
        f"({len(manifest.get('files', {}))} files).",
        "",
        "| label | git commit | model_version | thresholds (tau) | cold start s | RSS MB | "
        "image size MB | image ID |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for label in LABELS:
        r = results.get(label) or {}
        if not r.get("model_version"):
            out.append(f"| {label} | TODO | | | | | | |")
            continue
        tau = (r.get("thresholds") or {}).get("tau")
        out.append(
            f"| {label} | {r.get('git_commit')} | `{r['model_version']}` | "
            f"{_fmt(tau, 4) if tau is not None else ''} | {_fmt(r.get('cold_start_s'))} | "
            f"{_fmt(r.get('rss_mb'))} | {_fmt(r.get('image_size_mb'))} | "
            f"`{(r.get('image_id') or '')[:19]}` |")
    out += [
        "",
        "Cold start (local) = `docker run` to a healthy /health with the model loaded. Cold start "
        "(public) = script start to the first healthy answer after a Space restart; it excludes "
        "the Hugging Face build. RSS comes from `process_resident_memory_bytes` in /metrics. The "
        "public image is built by Hugging Face from the same staging directory, so its digest "
        "differs from the local image ID.",
        "",
        "Limitations of the free tier: the Space sleeps when idle (the first request after that "
        "waits for a cold start), the container disk is not persistent (the request log restarts "
        "empty), and CPU is shared, so latency varies between runs.",
        "",
    ]
    return "\n".join(out)


def load_results() -> dict[str, dict[str, Any]]:
    out = {}
    for label in LABELS:
        p = RESULTS / f"deployment_{label}.json"
        if p.is_file():
            out[label] = json.loads(p.read_text())
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Deployment record")
    ap.add_argument("--label", choices=LABELS, required=True)
    ap.add_argument("--url", help="public API URL (label public)")
    ap.add_argument("--ui-url", help="public reviewer UI URL (label public)")
    ap.add_argument("--docker-image", help="local serve image (label local)")
    ap.add_argument("--wait", type=float, default=600.0)
    args = ap.parse_args(argv)
    res: dict[str, Any] = {"label": args.label, "git_commit": _git_commit(),
                           "timestamp_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}
    if args.label == "local":
        if not args.docker_image:
            ap.error("--docker-image is required for the local label")
        res.update(image_info(args.docker_image))
        t0 = time.perf_counter()
        with Container(args.docker_image, {}) as c:
            cl = HttpClient(c.url)
            wait_healthy(cl, args.wait)
            res["cold_start_s"] = time.perf_counter() - t0
            res.update(collect(cl))
            cl.close()
    else:
        if not args.url:
            ap.error("--url is required for the public label")
        cl = HttpClient(args.url, timeout=60.0)
        res["cold_start_s"] = wait_healthy(cl, args.wait)
        res.update(collect(cl), url=args.url.rstrip("/"), ui_url=args.ui_url)
        cl.close()
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / f"deployment_{args.label}.json").write_text(
        json.dumps(res, indent=2, sort_keys=True) + "\n")
    REPORT.write_text(render(load_results()))
    print(f"{args.label}: model {res.get('model_version')}, cold start "
          f"{_fmt(res.get('cold_start_s'))} s, RSS {_fmt(res.get('rss_mb'))} MB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
