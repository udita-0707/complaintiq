"""Merge reports/experiments/*.csv into reports/m3/model_comparison.md.

Only numbers present in the experiment logs are written; empty cells stay empty.

Row status:
- current: logged with the fixed-label-set macro-F1 (notes contain "fixed label set").
- superseded: an older row whose model was re-scored; the rescore row replaces it.
- old definition: an older row that was not re-scored (its macro-F1 also counts classes
  that are only predicted); shown for the record, never ranked.

Usage: python scripts/compare_runs.py [--out reports/m3/model_comparison.md]
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

from complaintiq.eval.tracking import EXPERIMENTS_DIR, read_runs

REPO_ROOT = Path(__file__).resolve().parents[1]
BASELINE_MODEL = "baseline/tfidf_sgd"
METRIC_TAG = "fixed label set"
CONV_SUFFIX = "_conv"
METRICS = ("val_macro_f1", "val_macro_f1_all_labels", "val_weighted_f1", "val_top3", "val_pr_auc")
TASK_ORDER = ("product_class", "issue_class", "priority")
# Run-level caveats found after logging (the logged rows themselves are never edited).
KNOWN_ISSUES = {
    rid: "INVALID smoke: sampler u32 overflow under-sampled the largest classes"
    for rid in ("0f8cac1a34f3", "13b2926eb934", "ecb713cc3137")
}


def _f(v: str | None) -> float | None:
    return float(v) if v not in ("", None) else None


def _cell(v: str | None) -> str:
    x = _f(v)
    return "" if x is None else f"{x:.3f}"


def _hp(row: dict[str, str]) -> dict:
    try:
        return json.loads(row["hyperparams_json"] or "{}")
    except json.JSONDecodeError:
        return {}


def _conv(row: dict[str, str]) -> tuple[str, str, str]:
    """(n_iter, max_iter, converged) as display strings."""
    hp = _hp(row)
    n_iter, max_iter = hp.get("n_iter"), (hp.get("classifier") or {}).get("max_iter")
    if n_iter is None:
        return "", "", "n/a" if (hp.get("classifier") or {}).get("type") else ""
    conv = hp.get("converged")
    if conv is None:  # logged before convergence was recorded: infer from the cap
        conv_s = "no (hit cap)" if max_iter is not None and n_iter >= max_iter else "unknown"
    else:
        conv_s = "yes" if conv else "no (hit cap)"
    return str(n_iter), "" if max_iter is None else str(max_iter), conv_s


def _is_smoke(row: dict[str, str]) -> bool:
    return "smoke" in row.get("notes", "")


def classify(rows: list[dict[str, str]]) -> dict[str, str]:
    """run_id -> status text (``current``, ``superseded by <id>``, ``old definition``)."""
    replaced = {_hp(r).get("rescore_of"): r["run_id"] for r in rows if METRIC_TAG in r["notes"]}
    status = {}
    for r in rows:
        if METRIC_TAG in r["notes"]:
            status[r["run_id"]] = "current"
        elif r["run_id"] in replaced:
            status[r["run_id"]] = f"superseded by {replaced[r['run_id']]}"
        else:
            status[r["run_id"]] = "old definition (not rescored)"
    return status


def _family(model: str) -> str:
    return model[: -len(CONV_SUFFIX)] if model.endswith(CONV_SUFFIX) else model


def _key(task: str) -> str:
    return "val_pr_auc" if task == "priority" else "val_macro_f1"


def _table(rows: list[dict[str, str]], task: str, ref: dict[str, dict[str, str]],
           status: dict[str, str]) -> list[str]:
    key = _key(task)
    out = [
        "| run_id | model | n_train | " + " | ".join(METRICS)
        + f" | delta {key} | n_iter | max_iter | converged | train_s | status | notes |",
        "|" + "---|" * (len(METRICS) + 10),
    ]
    for r in sorted(rows, key=lambda r: -(_f(r[key]) or -1.0)):
        base = ref.get(r["n_train"])
        delta = ""
        if base is not None and base is not r and _f(r[key]) is not None:
            delta = f"{_f(r[key]) - _f(base[key]):+.3f}"
        n_iter, max_iter, conv = _conv(r)
        notes = " ".join(x for x in (KNOWN_ISSUES.get(r["run_id"], ""), r["notes"]) if x)
        secs = _f(r["train_seconds"])
        out.append(
            f"| {r['run_id']} | {r['model']} | {int(r['n_train'] or 0):,} | "
            + " | ".join(_cell(r.get(m)) for m in METRICS)
            + f" | {delta} | {n_iter} | {max_iter} | {conv} | "
            + ("" if secs is None else f"{secs:.1f}")
            + f" | {status[r['run_id']]} | {notes} |"
        )
    return out


def render(rows: list[dict[str, str]]) -> str:
    """Markdown for all logged runs, grouped by task."""
    status = classify(rows)
    out = [
        "# M3 model comparison (validation split)",
        "",
        "Generated by `python scripts/compare_runs.py` from `reports/experiments/*.csv`."
        " Every number is copied from a logged run; empty cells were not logged. All metrics"
        " are on **val**; the test split is not used in M3.",
        "",
        "- **`val_macro_f1`** is the mean F1 over the classes with val support (a fixed label"
        " set). `val_macro_f1_all_labels` also counts classes that are only predicted"
        " (product OTHER has no val rows). Rows logged before this definition was fixed"
        " are **superseded** by rescore rows (same saved model, no retraining, notes"
        " `rescored: fixed label set`) and are listed separately, never ranked.",
        "- Product and issue use argmax predictions. For priority, macro-F1 uses the fixed"
        " threshold 0.5; PR-AUC is threshold-free.",
        "- `converged` = the SGD tolerance stop fired before `max_iter`. `no (hit cap)` ="
        " sklearn ConvergenceWarning (or n_iter = max_iter for rows logged before this was"
        " recorded). `n/a` = not an iterative model (Complement NB).",
        f"- delta = run minus the current `{BASELINE_MODEL}` row with the same task and"
        " n_train.",
        "",
    ]
    by_task: dict[str, list[dict[str, str]]] = defaultdict(list)
    for r in rows:
        by_task[r["task"]].append(r)
    tasks = [t for t in TASK_ORDER if t in by_task] + sorted(set(by_task) - set(TASK_ORDER))
    for task in tasks:
        key = _key(task)
        cur = [r for r in by_task[task] if status[r["run_id"]] == "current"]
        old = [r for r in by_task[task] if status[r["run_id"]] != "current"]
        ref = {r["n_train"]: r for r in cur if r["model"] == BASELINE_MODEL}
        out += [f"## {task}", ""]
        full = [r for r in cur if not _is_smoke(r)]
        if full:
            best: dict[str, dict[str, str]] = {}
            for r in full:  # converged rerun replaces its capped variant in the ranking
                fam = _family(r["model"])
                if fam not in best or r["model"].endswith(CONV_SUFFIX):
                    best[fam] = r
            ranked = sorted(best.values(), key=lambda r: -(_f(r[key]) or -1.0))
            out += [
                f"### Ranking by {key} (full train, current definition; a converged rerun"
                " replaces its capped run)",
                "",
                f"| rank | variant | run used | {key} | delta vs baseline | converged |",
                "|---|---|---|---|---|---|",
            ]
            for i, r in enumerate(ranked, 1):
                base = ref.get(r["n_train"])
                delta = (
                    "" if base is None or base is r
                    else f"{_f(r[key]) - _f(base[key]):+.3f}"
                )
                out.append(
                    f"| {i} | {_family(r['model'])} | {r['model']} `{r['run_id']}` |"
                    f" {_cell(r[key])} | {delta} | {_conv(r)[2]} |"
                )
            out += ["", "### Full-train runs (current definition)", ""]
            out += _table(full, task, ref, status) + [""]
        smoke = [r for r in cur if _is_smoke(r)]
        if smoke:
            out += ["### Smoke runs (current definition)", ""]
            out += _table(smoke, task, ref, status) + [""]
        if old:
            out += ["### Superseded and old-definition rows (not ranked)", ""]
            out += _table(old, task, {}, status) + [""]
    return "\n".join(out).rstrip() + "\n"


def main() -> None:
    """CLI entry point."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--experiments-dir", default=str(EXPERIMENTS_DIR))
    ap.add_argument("--out", default=str(REPO_ROOT / "reports" / "m3" / "model_comparison.md"))
    args = ap.parse_args()
    rows = read_runs(args.experiments_dir)
    if not rows:
        raise SystemExit(f"no experiment logs in {args.experiments_dir}")
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(rows))
    print(f"wrote {out} ({len(rows)} runs)")


if __name__ == "__main__":
    main()
